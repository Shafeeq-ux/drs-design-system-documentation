// Brand icon fonts (IcoMoon exports) → brand-scoped glyph variables + one bridge stylesheet.
//
// Sources per brand (see tokens/brands/brands.json → icons):
//   tokens/brands/icons/<id>/style.css      IcoMoon CSS: .icon-<name>:before { content: "\e9xx" }
//   assets/iconfonts/<id>/<font>.woff|.ttf  the font files served to the browser
//   downloads/icons/<zip>                   the original export, offered as a download
//
// Every brand gets, inside its [data-brand] block, one pair of variables per icon name:
//   --aec-ig-<name>: "\e9xx"            the glyph
//   --aec-if-<name>: "<brand>-sc-icons"  the font (falls back to the default brand's font if this brand lacks the glyph)
// css/brand-icons.css then swaps .aec-icon's SVG mask for the glyph:
//   <span class="aec-icon" data-icon="car">  or the existing  style="--aec-icon-src:url(/assets/icons/car.svg)"
// Icons that no font contains keep their SVG mask.
import { readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

export const key = n => String(n).toLowerCase().replace(/^icon-/, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const loose = n => key(n).replace(/-/g, '');

export function loadIcons(root, reg) {
  const out = {};
  for (const b of reg.brands) {
    if (!b.icons) continue;
    const css = join(root, 'tokens/brands/icons', b.icons.dir, 'style.css');
    if (!existsSync(css)) continue;
    const map = {};
    for (const m of readFileSync(css, 'utf8').matchAll(/\.icon-([A-Za-z0-9_-]+):before\s*\{\s*content:\s*"\\([0-9a-fA-F]+)"/g)) map[key(m[1])] = m[2].toLowerCase();
    out[b.id] = { font: b.icons.font, dir: b.icons.dir, zip: b.icons.zip, map };
  }
  return out;
}

// Resolve the SVG library names (assets/icons/*.svg) to font glyph names
// Only glyphs the default brand has, so every brand can fall back to a real glyph
export function svgAliases(svgNames, icons, def) {
  const all = {};
  for (const n of Object.keys((icons[def] || {}).map || {})) all[loose(n)] = n;
  const alias = {};
  for (const s of svgNames) { const k = key(s); if (all[loose(k)]) alias[k] = all[loose(k)]; }
  return alias; // svg name → glyph name
}

export function iconVars(id, icons, def) {
  const own = icons[id], base = icons[def];
  if (!own && !base) return '';
  const names = new Set([...Object.keys((own || {}).map || {}), ...Object.keys((base || {}).map || {})]);
  const lines = [];
  for (const n of [...names].sort()) {
    const src = own && own.map[n] ? own : base;
    if (!src || !src.map[n]) continue;
    lines.push(`  --aec-ig-${n}: "\\${src.map[n]}";`, `  --aec-if-${n}: "${src.font}";`);
  }
  return `\n/* Icon font glyphs (${own ? own.font : base.font}) — tokens/brands/icons/${id}/ */\n[data-brand="${id}"] {\n  --aec-icon-font: "${(own || base).font}";\n${lines.join('\n')}\n}\n`;
}

export function iconBridge(icons, alias, def) {
  const out = ['/*', ' * DRS brand icons — GENERATED by scripts/build-brands.mjs (scripts/brand-icons.mjs). Do not edit by hand.', ' * Swaps .aec-icon SVG masks for the active brand\'s icon-font glyph. Glyph and font come from css/brands/<id>.css.', ' */', ''];
  for (const id of Object.keys(icons)) {
    const f = icons[id];
    out.push(`@font-face { font-family: "${f.font}"; src: url("../assets/iconfonts/${f.dir}/${f.font}.woff") format("woff"), url("../assets/iconfonts/${f.dir}/${f.font}.ttf") format("truetype"); font-weight: normal; font-style: normal; font-display: block; }`);
  }
  out.push('');
  // Fallback for any scope without its own glyph variables (e.g. the Theme builder preview): the default brand's glyphs
  if (def && icons[def]) out.push(iconVars(def, icons, def).replace(`[data-brand="${def}"]`, ':root'));
  const glyphs = new Set();
  for (const id of Object.keys(icons)) for (const n of Object.keys(icons[id].map)) glyphs.add(n);
  // svg name → glyph name (may differ in case/punctuation); every glyph is also reachable by its own name via data-icon
  const sel = {};
  for (const g of glyphs) sel[g] = [`[data-icon="${g}"]`];
  for (const [s, g] of Object.entries(alias)) sel[g].push(`[style*="/icons/${s}.svg"]`);
  out.push('[data-brand] .aec-icon[data-icon] { -webkit-mask: none; mask: none; background: none; }');
  out.push('[data-brand] .aec-icon[data-icon]::before { display: block; line-height: 1; }');
  for (const g of [...glyphs].sort()) {
    const s = sel[g].map(x => `[data-brand] .aec-icon${x}`).join(', ');
    out.push(`${s} { -webkit-mask: none; mask: none; background: none; display: inline-flex; align-items: center; justify-content: center; line-height: 1; font-size: var(--aec-icon-size, 24px); font-family: var(--aec-if-${g}); font-style: normal; font-weight: normal; text-transform: none; letter-spacing: 0; -webkit-font-smoothing: antialiased; }`);
    out.push(`${sel[g].map(x => `[data-brand] .aec-icon${x}::before`).join(', ')} { content: var(--aec-ig-${g}); }`);
  }
  return out.join('\n') + '\n';
}

export function iconData(icons, reg, alias, svgNames) {
  const brands = {};
  for (const b of reg.brands) {
    const f = icons[b.id]; if (!f) continue;
    brands[b.id] = { font: f.font, zip: f.zip, count: Object.keys(f.map).length, icons: Object.entries(f.map).sort((a, c) => a[0].localeCompare(c[0])).map(([name, code]) => [name, code]) };
  }
  const svgOnly = svgNames.map(key).filter(s => !alias[s]);
  return { brands, alias, svgOnly };
}
