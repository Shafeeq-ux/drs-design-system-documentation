// Builds the multi-brand layer from tokens/brands/brands.json + tokens/brands/source/<id>.css
//
//   css/brands/<id>.css            runtime tokens scoped to [data-brand="<id>"] (only what the site uses + every --aec-* var)
//   css/brand-components.css       bridge from brand tokens to .aec-* components (scripts/brand-bridge.mjs)
//   downloads/brands/<id>.css      the brand file as delivered (drop-in .drp-* classes + body vars)
//   downloads/brands/<id>.vars.css every token as a CSS custom property on :root
//   downloads/brands/<id>.json     every token as JSON
//   js/brands-data.js              registry for the header dropdown, Brand tokens page and Theme builder
//
// Every brand is merged over the default brand, so a brand that omits a token still renders.
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, readdirSync, unlinkSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { bridgeCSS } from './brand-bridge.mjs';
import { loadIcons, svgAliases, iconVars, iconBridge, iconData } from './brand-icons.mjs';

const require = createRequire(import.meta.url);
const B = require('../js/brand-core.js');
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const reg = JSON.parse(readFileSync(join(root, 'tokens/brands/brands.json'), 'utf8'));
const out = p => { mkdirSync(dirname(join(root, p)), { recursive: true }); return join(root, p); };

// 1. Parse every brand
const models = {};
for (const b of reg.brands) models[b.id] = B.parse(readFileSync(join(root, 'tokens/brands/source', b.file), 'utf8'));
const def = reg.default;
const baseTokens = B.tokens(models[def]);


// 2. Bridge (+ .drp-typography-* classes, generated from every brand's token names), so we know which --drp-* tokens the site consumes
const TYPE_PROPS = ['font-family', 'font-size', 'line-height', 'font-weight', 'letter-spacing', 'text-transform', 'text-decoration', 'text-indent'];
const typeStyles = [...new Set(Object.values(models).flatMap(m => B.tokens(m)).map(t => (t.name.match(/^--drp-typography-(.+)-font-size$/) || [])[1]).filter(Boolean))]
  .filter(n => !/^(mobile-)?(heading|display)-.+-regular$/.test(n)); // '… regular' selectors in the brand files match nothing
const typeCSS = ['', '/* Brand typography classes — the same names as the brand files (.drp-typography-*), driven by --drp-typography-* tokens */']
  .concat(typeStyles.map(n => `[data-brand] .drp-typography-${n} { ${TYPE_PROPS.map(p => `${p}: var(--drp-typography-${n}-${p});`).join(' ')} margin: 0; }`)).join('\n') + '\n';
const bridge = bridgeCSS() + typeCSS;
writeFileSync(out('css/brand-components.css'), bridge);
const used = new Set();
for (const f of ['css/components.css', 'css/patterns.css', 'css/docs.css', 'css/brand-components.css']) {
  for (const m of readFileSync(join(root, f), 'utf8').matchAll(/var\((--drp-[a-z0-9-]+)/g)) used.add(m[1]);
}

const isFamily = t => /font-family/.test(t.name);

// Icon fonts
const icons = loadIcons(root, reg);
const svgNames = readdirSync(join(root, 'assets/icons')).filter(f => f.endsWith('.svg')).map(f => f.slice(0, -4));
const alias = svgAliases(svgNames, icons, reg.default);
writeFileSync(out('css/brand-icons.css'), iconBridge(icons, alias, reg.default));
writeFileSync(out('js/icons-data.js'), `/* GENERATED by scripts/build-brands.mjs. Do not edit. */\nwindow.DRS_ICONS = ${JSON.stringify(iconData(icons, reg, alias, svgNames))};\n`);

// 3. Write outputs
const rtDir = join(root, 'css/brands');
const dlDir = join(root, 'downloads/brands');
for (const dir of [rtDir, dlDir]) { mkdirSync(dir, { recursive: true }); for (const f of readdirSync(dir)) unlinkSync(join(dir, f)); }

const registry = { default: def, brands: [], fonts: reg.fonts, generated: new Date().toISOString().slice(0, 10) };
for (const b of reg.brands) {
  const model = models[b.id];
  const own = B.tokens(model);
  const merged = new Map(baseTokens.map(t => [t.key, t]));
  for (const t of own) merged.set(t.key, t);
  const list = [...merged.values()];
  const map = Object.fromEntries(list.map(t => [t.key, t]));

  const runtime = B.runtimeCSS(list, {
    scope: `[data-brand="${b.id}"]`,
    fonts: reg.fonts,
    filter: t => t.layer === 'var' || used.has(t.name),
    header: `/* ${b.name} — runtime brand tokens. GENERATED by scripts/build-brands.mjs from tokens/brands/source/${b.file}. Do not edit. */`
  });
  writeFileSync(join(rtDir, `${b.id}.css`), runtime + iconVars(b.id, icons, reg.default));

  copyFileSync(join(root, 'tokens/brands/source', b.file), join(dlDir, `${b.id}.css`));
  writeFileSync(join(dlDir, `${b.id}.vars.css`), B.toVars(model, { header: `/* ${b.name} — DRS brand tokens as CSS custom properties (${own.length} tokens). Generated from ${b.file}. */` }));
  const meta = { id: b.id, name: b.name, description: b.description, source: b.file, generated: registry.generated };
  writeFileSync(join(dlDir, `${b.id}.json`), JSON.stringify(B.toJSON(model, meta), null, 2) + '\n');

  // Summary for the UI
  const v = k => (map[k] || {}).value;
  const families = [...new Set(own.filter(isFamily).map(t => B.firstFamily(t.value)))];
  registry.brands.push({
    id: b.id, name: b.name, description: b.description, file: b.file,
    tokens: own.length,
    primary: v('--aec-color-primary-default'), secondary: v('--aec-color-secondary-default'), action: v('--aec-color-action-bg-default'),
    text: v('--aec-color-text-default'), surface: v('--aec-color-bg-variant'),
    button: { bg: v('--drp-button-contained-color-primary-filled-background-color'), border: v('--drp-button-contained-color-primary-filled-border-color'), fg: v('--drp-button-contained-color-primary-filled-color'), radius: v('--drp-button-contained-container-bg-large-border-radius'), case: v('--drp-button-contained-typography-large-text-transform') },
    radius: v('--aec-border-radius-default'),
    fonts: { body: v('--aec-font-family-body'), heading: v('--aec-font-family-heading'), display: v('--aec-font-family-display'), button: v('--aec-font-family-button') },
    families,
    google: googleURL(families),
    icons: icons[b.id] ? { font: icons[b.id].font, zip: icons[b.id].zip, count: Object.keys(icons[b.id].map).length } : null
  });
}
function googleURL(families) {
  const q = [...new Set(families.map(f => (reg.fonts[f] || {}).google).filter(Boolean))];
  return q.length ? `https://fonts.googleapis.com/css2?${q.map(x => 'family=' + x).join('&')}&display=swap` : '';
}
writeFileSync(out('js/brands-data.js'), `/* GENERATED by scripts/build-brands.mjs. Do not edit. */\nwindow.DRS_BRANDS = ${JSON.stringify(registry, null, 2)};\n`);

const sizes = reg.brands.map(b => `${b.id} ${(readFileSync(join(rtDir, b.id + '.css')).length / 1024).toFixed(0)}KB`).join(', ');
console.log(`Typography: ${typeStyles.length} .drp-typography-* classes`);
console.log(`Icons: ${Object.keys(icons).length} fonts, ${Object.keys(alias).length} of ${svgNames.length} SVG names mapped to glyphs`);
console.log(`Built ${reg.brands.length} brands (${used.size} component tokens used by the site) — ${sizes}`);
