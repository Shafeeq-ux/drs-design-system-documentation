// Generates css/tokens.css and js/tokens-data.js from tokens/chevrolet.json.
// Run: node scripts/build-tokens.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const t = JSON.parse(readFileSync(join(root, 'tokens/chevrolet.json'), 'utf8'));
const P = `--${t.$meta.prefix}`;

const lines = [];
const colors = [];

// Colours: nested objects whose leaves carry { value }
function walkColor(node, path) {
  for (const [k, v] of Object.entries(node)) {
    if (v && typeof v === 'object' && 'value' in v) {
      const name = [...path, k].join('-');
      lines.push(`  ${P}-color-${name}: ${v.value};`);
      colors.push({ token: `${P}-color-${name}`, figma: [...path, k].join('/'), value: v.value, group: v.group, alias: v.alias || null });
    } else walkColor(v, [...path, k]);
  }
}

lines.push('  /* Colour */');
walkColor(t.color, []);

lines.push('', '  /* Border */');
for (const [k, v] of Object.entries(t.border.radius)) lines.push(`  ${P}-border-radius-${k}: ${v.value};`);
for (const [k, v] of Object.entries(t.border.width)) lines.push(`  ${P}-border-width-${k}: ${v.value};`);

lines.push('', '  /* Spacing */');
for (const [grp, props] of Object.entries(t.spacing))
  for (const [prop, sizes] of Object.entries(props))
    for (const [s, v] of Object.entries(sizes)) lines.push(`  ${P}-spacing-${grp}-${prop}-${s}: ${v};`);

lines.push('', '  /* Sizing */');
for (const [grp, sizes] of Object.entries(t.sizing))
  for (const [s, v] of Object.entries(sizes)) lines.push(`  ${P}-sizing-${grp}-${s}: ${v};`);

lines.push('', '  /* Elevation */');
for (const [k, v] of Object.entries(t['box-shadow'])) lines.push(`  ${P}-box-shadow-${k}: ${v};`);

lines.push('', '  /* Font */');
for (const [k, v] of Object.entries(t.font.family)) lines.push(`  ${P}-font-family-${k}: ${v};`);
for (const [k, v] of Object.entries(t.font.weight)) lines.push(`  ${P}-font-weight-${k}: ${v};`);

// Typography: mobile-first; desktop values from the tablet breakpoint (tablet == desktop in Figma)
const px = n => `${n}px`;
const typeVars = (bp) => {
  const out = [];
  for (const [name, spec] of Object.entries(t.typography)) {
    const v = spec[bp] || (bp === 'mobile' ? spec.desktop : null);
    if (!v) continue;
    if (bp === 'desktop' && spec.mobile && spec.mobile.join() === spec.desktop.join()) continue;
    if (bp === 'desktop' && !spec.mobile) continue;
    const [size, lh, weight, ls] = v;
    out.push(`  ${P}-typography-${name}-font-size: ${px(size)};`);
    out.push(`  ${P}-typography-${name}-line-height: ${px(lh)};`);
    out.push(`  ${P}-typography-${name}-font-weight: var(${P}-font-weight-${weight});`);
    out.push(`  ${P}-typography-${name}-letter-spacing: ${ls ? px(ls) : '0'};`);
  }
  return out;
};

lines.push('', '  /* Typography (mobile first) */');
lines.push(...typeVars('mobile'));

const css = `/*
 * ${t.$meta.name} — design tokens
 * Generated by scripts/build-tokens.mjs from tokens/chevrolet.json. Do not edit by hand.
 * Source: ${t.$meta.source}
 */
:root {
${lines.join('\n')}
}

@media (min-width: ${t.breakpoint.tablet}) {
  :root {
${typeVars('desktop').map(l => '  ' + l).join('\n')}
  }
}
`;

writeFileSync(join(root, 'css/tokens.css'), css);

// Data for the docs pages (swatches, tables)
const typography = Object.entries(t.typography).map(([name, s]) => ({ name, ...s }));
const data = {
  colors,
  radius: Object.entries(t.border.radius).map(([k, v]) => ({ token: `${P}-border-radius-${k}`, value: v.value, alias: v.alias || null })),
  width: Object.entries(t.border.width).map(([k, v]) => ({ token: `${P}-border-width-${k}`, value: v.value, alias: v.alias || null })),
  spacing: Object.entries(t.spacing).flatMap(([g, props]) => Object.entries(props).flatMap(([p, sizes]) => Object.entries(sizes).map(([s, v]) => ({ group: g, prop: p, size: s, token: `${P}-spacing-${g}-${p}-${s}`, value: v })))),
  shadow: Object.entries(t['box-shadow']).map(([k, v]) => ({ token: `${P}-box-shadow-${k}`, name: k, value: v })),
  typography,
  weights: t.font.weight
};
writeFileSync(join(root, 'js/tokens-data.js'), `// Generated by scripts/build-tokens.mjs. Do not edit by hand.\nwindow.AEC_TOKENS = ${JSON.stringify(data, null, 2)};\n`);

console.log(`tokens.css: ${lines.filter(l => l.includes(':')).length} declarations, ${colors.length} colours`);
